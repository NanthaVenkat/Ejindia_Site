                <h3 class="text-md sm:text-lg text-white">ii. Remuneration to Non-Executive / Independent Directors</h3>
                <ol class="!pl-4">
                    <li>
                        <p>The Non-Executive / Independent Directors may receive sitting fees and such other remuneration as permissible under the provisions of Companies Act, 2013 [Subject to the approval of the Board of Directors]. The amount of sitting fees shall be such as may be recommended by the Nomination and Remuneration Committee and approved by the Board of Directors.</p>

                    </li>
                    <li>
                        <p>All the remuneration of the Non-Executive / Independent Directors (excluding remuneration for attending meetings as prescribed under Section 197 (5) of the Companies Act, 2013) shall be subject to ceiling/ limits as provided under Companies Act, 2013 and rules made there under or any other enactment for the time being in force. The amount of such remuneration shall be such as may be recommended by the Nomination and Remuneration Committee and approved by the Board of Directors or shareholders, as the case may be.</p>

                    </li>
                    <li>
                        <p>An Independent Director shall not be eligible to get Stock Options and also shall not be eligible to participate in any share based payment schemes of the Company.</p>

                    </li>
                    <li>
                        <p>Any remuneration paid to Non-Executive / Independent Directors for services rendered which are of professional in nature shall not be considered as part of the remuneration for the purposes of clause (ii) above if the following conditions are satisfied:</p>

