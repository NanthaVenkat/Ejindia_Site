                <ol class="!pl-4">
                    <li>
                        <p>The remuneration to Key Managerial Personnel and Senior Management shall consist of fixed pay and incentive pay, in compliance with the provisions of the Companies Act, 2013 and in accordance with the Company’s Policy.</p>

                    </li>
                    <li>
                        <p>The Compensation Committee of the Company, constituted for the purpose of administering the Employee Stock Option/ Purchase Schemes, shall determine the stock options and other share based payments to be made to Key Managerial Personnel and Senior Management.</p>

                    </li>
                    <li>
                        <p>The Fixed pay shall include monthly remuneration, employer’s contribution to Provident Fund, contribution to pension fund, pension schemes, etc. as decided from to time.</p>

                    </li>
                    <li>
                        <p>The Incentive pay shall be decided based on the balance between performance of the Company and performance of the Key Managerial Personnel and Senior Management, to be decided annually or at such intervals as may be considered appropriate.</p>

                    </li>
                </ol>
