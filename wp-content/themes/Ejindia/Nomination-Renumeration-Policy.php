            <section class="space-y-4">
                <h2 class="text-md sm:text-lg text-white">TERM / TENURE</h2>

                <h3 class="text-md sm:text-lg text-white">Managing Director / Whole-time Director</h3>
                <p>The Company shall appoint or re-appoint any person as its Executive Chairman, Managing Director or Executive Director for a term not exceeding five years at a time. No re-appointment shall be made earlier than one year before the expiry of term.</p>

                <h3 class="text-md sm:text-lg text-white">INDEPENDENT DIRECTOR</h3>
                <p>An Independent Director shall hold office for a term up to five consecutive years on the Board of the Company and will be eligible for re-appointment on passing of a special resolution by the Company and disclosure of such appointment in the Board's report. No Independent Director shall hold office for more than two consecutive terms of up to a maximum of five years each, but such Independent Director shall be eligible for appointment after expiry of three years of ceasing to become an Independent Director. Provided that an Independent Director shall not, during the said period of three years, be appointed in or be associated with the Company in any other capacity, either directly or indirectly.</p>

                <p>At the time of appointment of Independent Director it should be ensured that number of Boards on which such Independent Director serves is restricted to seven listed companies as an Independent Director and three listed companies as an Independent Director in case such person is serving as a Whole-time Director of a listed company or such other number as may be prescribed under the Act.</p>

                <p><strong>Evaluation</strong> — The Committee shall carry out evaluation of performance of Director, KMP and Senior Management Personnel yearly or at such intervals as may be considered necessary.</p>

