                <h3 class="text-md sm:text-lg text-white">i. Remuneration to Managing Director / Whole-time Directors</h3>
                <ol class="!pl-4">
                    <li>
                        <p>The Remuneration/ Commission etc. to be paid to Managing Director / Whole-time Directors, etc. shall be governed as per provisions of the Companies Act, 2013 and rules made there under or any other enactment for the time being in force and the approvals obtained from the Members of the Company.</p>

                    </li>
                    <li>
                        <p>The Nomination and Remuneration Committee shall make such recommendations to the Board of Directors, as it may consider appropriate with regard to remuneration to Managing Director / Whole-time Directors.</p>

