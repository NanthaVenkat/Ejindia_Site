                <p>This Nomination and Remuneration Policy is being formulated in compliance with Section 178 of the Companies Act, 2013 read along with the applicable rules thereto, as amended from time to time. This policy on nomination and remuneration of Directors, Key Managerial Personnel and Senior Management has been formulated by the Nomination and Remuneration Committee (NRC or the Committee) and has been approved by the Board of Directors.</p>

