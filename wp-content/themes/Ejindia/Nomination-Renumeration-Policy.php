            <section class="space-y-4">
                <h2 class="text-md sm:text-lg text-white">OBJECTIVE</h2>

                <ol class="!pl-4">
                    <li>
                        <p>To guide the Board in relation to appointment and removal of Directors, Key Managerial Personnel and Senior Management.</p>
                    </li>
                    <li>
                        <p>To evaluate the performance of the members of the Board and provide necessary report to the Board for further evaluation of the Board.</p>
                    </li>
                    <li>
                        <p>To recommend to the Board on Remuneration payable to the Directors, Key Managerial Personnel and Senior Management.</p>
                    </li>
                </ol>
            </section>

            <section class="space-y-4">
                <h2 class="text-md sm:text-lg text-white">ROLE OF THE COMMITTEE</h2>

                <p>The role of the NRC will be the following:</p>

                <ol class="!pl-4">
                    <li>
                        <p>To formulate criteria for determining qualifications, positive attributes and independence of a Director.</p>

                    </li>
                    <li>
                        <p>To formulate criteria for evaluation of Independent Directors and the Board.</p>
                    </li>
                    <li>
                        <p>To identify persons who are qualified to become Directors and who may be appointed in Senior Management in accordance with the criteria laid down in this policy.</p>
                    </li>
                    <li>
                        <p>To carry out evaluation of Director’s performance.</p>
                    </li>
                    <li>
                        <p>To recommend to the Board the appointment and removal of Directors and Senior Management.</p>
                    </li>
                    <li>
                        <p>To recommend to the Board policy relating to remuneration for Directors, Key Managerial Personnel and Senior Management.</p>
                    </li>
                    <li>
                        <p>To devise a policy on Board diversity, composition, size.</p>
                    </li>
                    <li>
                        <p>Succession planning for replacing Key Executives and overseeing.</p>
                    </li>
                    <li>
                        <p>To carry out any other function as is mandated by the Board from time to time and / or enforced by any statutory notification, amendment or modification, as may be applicable.</p>
                    </li>
                    <li>
                        <p>To perform such other functions as may be necessary or appropriate for the performance of its duties.</p>
                    </li>
                </ol>
