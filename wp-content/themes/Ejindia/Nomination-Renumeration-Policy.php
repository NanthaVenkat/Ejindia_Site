                    </li>
                    <li>
                        <p>A person should possess adequate qualification, expertise and experience for the position he / she is considered for appointment. The Committee has authority to decide whether qualification, expertise and experience possessed by a person is sufficient/satisfactory for the position.</p>
                    </li>
                    <li>
                        <p>The Company shall not appoint or continue the employment of any person as Whole-time Director who has attained the age of seventy years. Provided that the term of the person holding this position may be extended beyond the age of seventy years with the approval of shareholders by passing a special resolution.</p>
                    </li>
                </ol>
