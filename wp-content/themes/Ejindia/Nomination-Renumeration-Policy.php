                <p><strong>“Key Managerial Personnel”</strong> means</p>

                <ol class="!pl-4">
                    <li>the Chief Executive Officer or the Managing director or the Manager</li>
                    <li>the Company Secretary</li>
                    <li>the Whole-Time Director</li>
                    <li>the Chief Financial Officer</li>
                    <li>such other officer as may be prescribed.</li>
                </ol>
                <p><strong>“Senior Managerial Personnel”</strong> mean the personnel of the company who are members of its core management team excluding Board of Directors. Normally, this would comprise all members of management, of rank equivalent to General Manager and above, including all functional heads.</p>

